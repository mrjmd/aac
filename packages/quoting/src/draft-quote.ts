/**
 * draft-quote — quote drafter v1.
 *
 * Turns a customer text thread (+ MMS photos) into a bot-marked Pending
 * estimate in QBO. Nothing here is customer-facing: the draft exists only
 * for the owner's review, flagged by a DescriptionOnly line at the top
 * and a PrivateNote explaining the reasoning.
 *
 * Pure functions — the runner (tools/src/drafter) does all I/O: fetching
 * the Quo thread, downloading photos, calling Gemini, and creating the
 * estimate via QuickBooksClient.
 *
 * Pricing authority is the canonical ruleset's SECTION 0
 * (analysis/data/quoting-spike/llm-ruleset.md), passed in as text. The
 * validator independently enforces the discount formula so a drifting
 * LLM can't reintroduce the old discount habits.
 */

import type { QBEstimate, QBEstimateCreateLine, QBItem } from '@aac/api-clients/quickbooks';

// ── constants ────────────────────────────────────────────────────────

/** Idempotency marker — present in the top line and the PrivateNote. */
export const BOT_DRAFT_MARKER = 'BOT DRAFT';

/** Top DescriptionOnly line on every drafted estimate. */
export const BOT_DRAFT_TOP_LINE =
  '⚠️ BOT DRAFT — REVIEW BEFORE SENDING ⚠️ (generated by quote drafter v1 — delete this line before sending)';

/** Fixed multi-injection discount per Section 0 rule 3. */
const DISCOUNT_PER_INJECTION = 75;
const DISCOUNT_MIN_INJECTIONS = 3;

// Injection-unit counting for the discount rule: wall/structure injection
// work counts; floor/slab routing, tie holes, and surface sealing don't.
const INJECTION_ITEM_RE = /crack repair|injection/i;
const NON_DISCOUNTABLE_RE = /floor|slab|tie hole|surface seal|spot injection/i;

// ── types ────────────────────────────────────────────────────────────

export interface DraftThreadMessage {
  direction: 'incoming' | 'outgoing';
  at: string;
  text: string;
}

export interface QuoteDraftLine {
  /** QBO item name — must resolve against the live item menu. */
  item: string;
  /** Scope-specific description; canonical library text fills gaps. */
  description?: string;
  qty: number;
  unitPrice: number;
}

export interface QuoteDraft {
  scopeSummary: string;
  lines: QuoteDraftLine[];
  needsSiteVisit: boolean;
  reasoning: string;
  openQuestions: string[];
  confidence: 'high' | 'medium' | 'low';
}

export interface DraftValidation {
  /** False = do not create the estimate (unknown items, no sales lines). */
  ok: boolean;
  errors: string[];
  /** Corrections applied or review flags — surfaced in the PrivateNote. */
  warnings: string[];
  draft: QuoteDraft;
}

export interface ComparableSummary {
  docNumber: string;
  txnDate: string;
  txnStatus: string;
  total: number;
  itemSummary: string;
}

// ── prompt ───────────────────────────────────────────────────────────

export function buildQuoteDraftPrompt(args: {
  customerName: string;
  phone: string;
  today: string;
  rulesetText: string;
  itemNames: string[];
  thread: DraftThreadMessage[];
  photoCount: number;
}): { systemPrompt: string; userPrompt: string } {
  const systemPrompt = `You draft quotes for Attack A Crack, a foundation-repair company in Quincy MA. Matt is the owner. You are given a customer SMS thread (OUT = Matt, IN = customer)${args.photoCount > 0 ? ` and ${args.photoCount} photos the customer texted in` : ''}. Today is ${args.today}.

Draft the estimate Matt would write, as line items. PRICING AUTHORITY is SECTION 0 of the ruleset below — where Sections 1-2 disagree with Section 0, Section 0 wins. Use the photos to count cracks and judge scope (full-height vs partial, slab vs wall).

RULESET:
${args.rulesetText}

Each line's "item" MUST be one of these QBO item names (exact spelling):
${args.itemNames.join(' | ')}

Hard rules:
- Draft ONLY repairs the thread or photos give concrete evidence for. NEVER infer a repair from the mere presence of a structure. Specifically: a bulkhead alone is NOT a reason for Bulkhead Injection — the indicators are water entry at the sides of the bulkhead-to-foundation seam, at the bolts into the basement, or at the bottom of the stairs. No indicator, no line.
- NEVER add a discount line on a job with fewer than ${DISCOUNT_MIN_INJECTIONS} injection units. At ${DISCOUNT_MIN_INJECTIONS}+, the Discount line is exactly -$${DISCOUNT_PER_INJECTION} per injection unit — never resized to hit a round total.
- NEVER add a cash/check discount (payment method is unknown at draft time).
- Do NOT include a Guarantee line — it is appended automatically.
- One line per service with qty (e.g. 3 cracks = Crack Repair qty 3), not three separate lines.
- Line descriptions are NOT used on the estimate — each item's standard QBO description template is inserted verbatim. You may omit "description"; anything scope-specific belongs in scope_summary/reasoning instead.
- If the thread/photos don't support a confident price (fieldstone, bowing walls, unclear scope, $4k+ complexity), set needs_site_visit true and list what's unknown in open_questions — still draft your best-guess lines.
- If the thread mentions wall bowing over 1.5 inches, drainage/grading as the root cause, or work AAC doesn't do, say so in open_questions.

Respond with ONLY a JSON object:
{"scope_summary": "1-2 sentences", "lines": [{"item": "QBO item name", "description": "scope text", "qty": number, "unit_price": number}], "needs_site_visit": boolean, "reasoning": "which Section 0 rules you applied and why", "open_questions": ["..."], "confidence": "high"|"medium"|"low"}`;

  const digest = args.thread
    .map((m) => `${m.direction === 'outgoing' ? 'OUT' : 'IN'} ${m.at.slice(0, 16)}: ${m.text}`)
    .join('\n');

  const userPrompt = `CUSTOMER: ${args.customerName} (${args.phone})
${args.photoCount > 0 ? `PHOTOS: ${args.photoCount} attached (oldest first)\n` : ''}THREAD:
${digest}`;

  return { systemPrompt, userPrompt };
}

// ── parse ────────────────────────────────────────────────────────────

/**
 * Parse the model's JSON reply. Tolerates markdown fences and leading
 * prose; returns null when no parseable draft is present.
 */
export function parseQuoteDraftResponse(raw: string): QuoteDraft | null {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start < 0 || end <= start) return null;

  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(raw.slice(start, end + 1)) as Record<string, unknown>;
  } catch {
    return null;
  }

  const rawLines = Array.isArray(parsed.lines) ? parsed.lines : [];
  const lines: QuoteDraftLine[] = [];
  for (const l of rawLines) {
    if (typeof l !== 'object' || l === null) continue;
    const rec = l as Record<string, unknown>;
    const item = typeof rec.item === 'string' ? rec.item.trim() : '';
    const qty = Number(rec.qty ?? 1);
    const unitPrice = Number(rec.unit_price ?? rec.unitPrice);
    if (!item || !Number.isFinite(qty) || !Number.isFinite(unitPrice)) continue;
    lines.push({
      item,
      description: typeof rec.description === 'string' ? rec.description : undefined,
      qty,
      unitPrice,
    });
  }
  if (lines.length === 0) return null;

  const confidence = parsed.confidence === 'high' || parsed.confidence === 'low' ? parsed.confidence : 'medium';
  return {
    scopeSummary: typeof parsed.scope_summary === 'string' ? parsed.scope_summary : '',
    lines,
    needsSiteVisit: parsed.needs_site_visit === true,
    reasoning: typeof parsed.reasoning === 'string' ? parsed.reasoning : '',
    openQuestions: Array.isArray(parsed.open_questions)
      ? parsed.open_questions.filter((q): q is string => typeof q === 'string')
      : [],
    confidence,
  };
}

// ── validate ─────────────────────────────────────────────────────────

function isDiscountItem(name: string): boolean {
  return /^discount$/i.test(name.trim());
}

function isGuaranteeItem(name: string): boolean {
  return /guarantee/i.test(name);
}

/** Injection units for the discount formula (qty-weighted). */
export function countInjectionUnits(lines: QuoteDraftLine[]): number {
  return lines
    .filter((l) => INJECTION_ITEM_RE.test(l.item) && !NON_DISCOUNTABLE_RE.test(l.item))
    .reduce((sum, l) => sum + l.qty, 0);
}

/**
 * Normalize + enforce Section 0 deterministically. Unknown items are hard
 * errors (the runner skips creation); discount-rule violations are
 * corrected in place and reported as warnings.
 */
export function validateQuoteDraft(draft: QuoteDraft, itemNames: string[]): DraftValidation {
  const errors: string[] = [];
  const warnings: string[] = [];
  const byLower = new Map(itemNames.map((n) => [n.toLowerCase(), n]));

  const lines: QuoteDraftLine[] = [];
  for (const line of draft.lines) {
    // The canonical Guarantee line is appended by the assembler.
    if (isGuaranteeItem(line.item)) continue;

    const canonical = byLower.get(line.item.toLowerCase());
    if (!canonical) {
      errors.push(`Unknown QBO item "${line.item}" — not in the live item menu`);
      continue;
    }
    if (!isDiscountItem(canonical) && (line.qty <= 0 || line.unitPrice < 0)) {
      warnings.push(`Dropped nonsensical line: ${canonical} qty ${line.qty} @ ${line.unitPrice}`);
      continue;
    }
    lines.push({ ...line, item: canonical });
  }

  // Discount rule (Section 0 rule 3): only at 3+ injection units, exactly
  // −$75 per unit. Cash discounts never appear at draft time.
  const salesLines = lines.filter((l) => !isDiscountItem(l.item));
  const discountLines = lines.filter((l) => isDiscountItem(l.item));
  const units = countInjectionUnits(salesLines);
  const finalLines: QuoteDraftLine[] = [...salesLines];

  if (discountLines.length > 0) {
    if (units < DISCOUNT_MIN_INJECTIONS) {
      warnings.push(
        `Stripped discount line — only ${units} injection unit(s), rule requires ${DISCOUNT_MIN_INJECTIONS}+`,
      );
    } else {
      const expected = DISCOUNT_PER_INJECTION * units;
      const proposed = Math.abs(discountLines.reduce((s, d) => s + d.qty * d.unitPrice, 0));
      if (Math.round(proposed) !== expected) {
        warnings.push(
          `Corrected discount to formula: -$${expected} (${units} × $${DISCOUNT_PER_INJECTION}); model proposed -$${Math.round(proposed)}`,
        );
      }
      finalLines.push({
        item: discountLines[0].item,
        description: 'Multiple injection discount.',
        qty: 1,
        unitPrice: -expected,
      });
    }
  }

  if (finalLines.filter((l) => !isDiscountItem(l.item)).length === 0) {
    errors.push('Draft has no sales lines after validation');
  }

  return { ok: errors.length === 0, errors, warnings, draft: { ...draft, lines: finalLines } };
}

// ── assemble ─────────────────────────────────────────────────────────

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

export function draftTotal(draft: QuoteDraft): number {
  return round2(draft.lines.reduce((s, l) => s + l.qty * l.unitPrice, 0));
}

/**
 * Most recent real (non-bot) description per item name, for filling
 * lines the model left terse. Estimates must be newest-first.
 */
export function buildDescriptionLibrary(estimates: QBEstimate[]): Map<string, string> {
  const lib = new Map<string, string>();
  for (const e of estimates) {
    if (isBotDraft(e)) continue;
    for (const line of e.Line ?? []) {
      const name = line.SalesItemLineDetail?.ItemRef?.name;
      if (!name || !line.Description || lib.has(name)) continue;
      lib.set(name, line.Description);
    }
  }
  return lib;
}

export function isBotDraft(e: QBEstimate): boolean {
  if (e.PrivateNote?.includes(BOT_DRAFT_MARKER)) return true;
  return (e.Line ?? []).some(
    (l) => l.DetailType === 'DescriptionOnly' && l.Description?.includes(BOT_DRAFT_MARKER),
  );
}

/**
 * Build the QBO create payload: bot marker first, sales lines (canonical
 * descriptions where the model gave none), Guarantee last.
 */
export function assembleEstimateLines(args: {
  draft: QuoteDraft;
  items: QBItem[];
  descriptionLibrary: Map<string, string>;
}): QBEstimateCreateLine[] {
  const itemByLower = new Map(args.items.map((i) => [i.Name.toLowerCase(), i]));

  const lines: QBEstimateCreateLine[] = [
    { DetailType: 'DescriptionOnly', Description: BOT_DRAFT_TOP_LINE, DescriptionLineDetail: {} },
  ];

  for (const line of args.draft.lines) {
    const item = itemByLower.get(line.item.toLowerCase());
    if (!item) throw new Error(`assembleEstimateLines: unresolved item "${line.item}" — validate first`);
    lines.push({
      DetailType: 'SalesItemLineDetail',
      // Owner rule (2026-10-16): the standard QBO item template verbatim,
      // never model-rewritten. Recent-estimate wording covers items with
      // no template; model text is a last resort only.
      Description: item.Description || args.descriptionLibrary.get(item.Name) || line.description,
      Amount: round2(line.qty * line.unitPrice),
      SalesItemLineDetail: {
        ItemRef: { value: item.Id, name: item.Name },
        Qty: line.qty,
        UnitPrice: line.unitPrice,
      },
    });
  }

  const guarantee = args.items.find((i) => isGuaranteeItem(i.Name));
  const guaranteeText = guarantee && (guarantee.Description || args.descriptionLibrary.get(guarantee.Name));
  if (guarantee && guaranteeText) {
    lines.push({
      DetailType: 'SalesItemLineDetail',
      Description: guaranteeText,
      Amount: 0,
      SalesItemLineDetail: { ItemRef: { value: guarantee.Id, name: guarantee.Name }, Qty: 1, UnitPrice: 0 },
    });
  }

  return lines;
}

// ── comparables + private note ───────────────────────────────────────

/**
 * Recent real estimates sharing at least one item with the draft —
 * review context for the PrivateNote ("your last similar jobs ran $X").
 */
export function selectComparables(
  estimates: QBEstimate[],
  draft: QuoteDraft,
  max = 3,
): ComparableSummary[] {
  const draftItems = new Set(
    draft.lines.filter((l) => !isDiscountItem(l.item)).map((l) => l.item.toLowerCase()),
  );

  const out: ComparableSummary[] = [];
  for (const e of estimates) {
    if (isBotDraft(e)) continue;
    const saleLines = (e.Line ?? []).filter((l) => l.SalesItemLineDetail?.ItemRef?.name);
    const names = saleLines.map((l) => l.SalesItemLineDetail!.ItemRef!.name!);
    if (!names.some((n) => draftItems.has(n.toLowerCase()))) continue;

    out.push({
      docNumber: e.DocNumber ?? e.Id,
      txnDate: e.TxnDate ?? '',
      txnStatus: e.TxnStatus ?? '?',
      total: e.TotalAmt ?? 0,
      itemSummary: saleLines
        .filter((l) => !isGuaranteeItem(l.SalesItemLineDetail!.ItemRef!.name!))
        .map((l) => {
          const d = l.SalesItemLineDetail!;
          const qty = d.Qty ?? 1;
          return `${d.ItemRef!.name}${qty !== 1 ? ` ×${qty}` : ''} @$${d.UnitPrice ?? l.Amount}`;
        })
        .join(', '),
    });
    if (out.length >= max) break;
  }
  return out;
}

export function buildDraftPrivateNote(args: {
  draft: QuoteDraft;
  warnings: string[];
  comparables: ComparableSummary[];
  generatedAt: string;
}): string {
  const { draft } = args;
  const parts: string[] = [
    `${BOT_DRAFT_MARKER} — quote drafter v1 (${args.generatedAt}). REVIEW BEFORE SENDING.`,
    `Scope: ${draft.scopeSummary}`,
    `Total: $${draftTotal(draft)} | Confidence: ${draft.confidence}${draft.needsSiteVisit ? ' | SITE VISIT RECOMMENDED' : ''}`,
    `Reasoning: ${draft.reasoning}`,
  ];
  if (args.comparables.length > 0) {
    parts.push(
      'Recent similar estimates:',
      ...args.comparables.map(
        (c) => `- #${c.docNumber} ${c.txnDate} ${c.txnStatus} $${c.total} — ${c.itemSummary}`,
      ),
    );
  }
  if (draft.openQuestions.length > 0) {
    parts.push('Open questions:', ...draft.openQuestions.map((q) => `- ${q}`));
  }
  if (args.warnings.length > 0) {
    parts.push('Auto-corrections:', ...args.warnings.map((w) => `- ${w}`));
  }
  return parts.join('\n');
}
